#!/usr/bin/env node
// inspect-metadata.mjs - titles, descriptions, canonicals, robots.txt, sitemap.xml, noindex, Open Graph,
// Twitter cards, favicon, JSON-LD parseability - and how they contradict each other.
// The value is in the relationships (a private route listed in the sitemap, a localhost canonical,
// a noindex page in the sitemap, robots blocking a page the sitemap advertises), not file existence.
//
//   node inspect-metadata.mjs --url http://localhost:3000 [--render] [--json]
//   node inspect-metadata.mjs --dir ./dist [--json]

import { parseArgs } from "node:util";
import { emit, finding, usageError } from "./lib/report.mjs";
import { findAll, findFirst, metaContent, parseHtml, textOf } from "./lib/html.mjs";
import { extractLocs, fetchWithRetry, loadSite, normalizePath, siteNotRead } from "./lib/pages.mjs";

const { values: args } = parseArgs({
  options: {
    url: { type: "string" },
    dir: { type: "string" },
    render: { type: "boolean", default: false },
    "max-pages": { type: "string", default: "40" },
    timeout: { type: "string", default: "10000" },
    "chrome-path": { type: "string" },
    "private-path": { type: "string", multiple: true, default: [] },
    json: { type: "boolean", default: false },
  },
});
if (!args.url && !args.dir) usageError("Usage: inspect-metadata.mjs --url <site> | --dir <build dir> [--render] [--private-path /x] [--json]");

const STARTER_TITLE = /^(vite\s*\+.*|vite app|react app|create next app|next\.?js( app)?|document|untitled( document)?|index|my app|my website|welcome|localhost.*|astro|sveltekit.*|nuxt.*|your (app|site|company|website).*|lovable( app)?|v0 app|bolt.*|base44.*|.*generated by create next app.*|.*lorem ipsum.*|title|site title|website|home page)$/i;
const PLACEHOLDER_DESC = /lorem ipsum|web site created using create-react-app|generated by create next app|description goes here|your (description|tagline|website description)|add (a )?description|todo|placeholder/i;
const DEV_HOST = /^(localhost|127\.0\.0\.1|0\.0\.0\.0|\[::1\]|.*\.local|.*\.localhost)$/i;
const STAGING_HOST = /(^|\.)(staging|stage|dev|preview|qa|uat|test|sandbox)\./i;
const PLATFORM_HOST = /\.(vercel\.app|netlify\.app|pages\.dev|github\.io|onrender\.com|railway\.app|fly\.dev|replit\.app|repl\.co|lovable\.app|lovable\.dev|bolt\.host|web\.app|firebaseapp\.com|herokuapp\.com|surge\.sh|glitch\.me)$/i;
const HIGH_PRIVATE = /(^|\/)(admin|wp-admin|dashboard|internal|api|debug|staging|_next|preview|drafts?|console|backoffice|test)(\/|$)/i;
const MEDIUM_PRIVATE = /(^|\/)(login|log-in|signin|sign-in|register|reset-password|forgot-password|verify|account|accounts|settings|profile|checkout|cart|thank-you|thanks|success|onboarding|auth|callback|confirm|unsubscribe)(\/|$)/i;
const STARTER_ASSET = /(vite|react|next|vercel|placeholder|default|logo192|logo512)\.(svg|png|ico)$/i;
const extraPrivate = args["private-path"].map((p) => normalizePath(p));

const site = await loadSite({
  url: args.url,
  dir: args.dir,
  render: args.render,
  maxPages: Number(args["max-pages"]),
  timeoutMs: Number(args.timeout),
  chromePath: args["chrome-path"],
}).catch((error) => usageError(error.message));

const findings = [];
const notes = [...site.notes];
const unread = siteNotRead(site);
if (unread) findings.push(unread);
const add = (code, severity, evidence, message, extra) => findings.push(finding(code, severity, evidence, message, extra));
const pages = site.pages.filter((p) => p.status === 200 && p.html);
if (pages.length === 0) notes.push("No HTML pages could be read. Check the URL/directory, or use --render for client-rendered sites.");

// ---------- robots.txt parsing ----------
function parseRobots(text) {
  const groups = [];
  let current = null;
  const sitemaps = [];
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.replace(/#.*$/, "").trim();
    if (!line) continue;
    const idx = line.indexOf(":");
    if (idx < 0) continue;
    const key = line.slice(0, idx).trim().toLowerCase();
    const value = line.slice(idx + 1).trim();
    if (key === "user-agent") {
      if (!current || current.rules.length) {
        current = { agents: [], rules: [] };
        groups.push(current);
      }
      current.agents.push(value.toLowerCase());
    } else if ((key === "disallow" || key === "allow") && current) current.rules.push({ type: key, value });
    else if (key === "sitemap") sitemaps.push(value);
  }
  return { groups, sitemaps };
}

function ruleRegex(value) {
  const escaped = value.replace(/[.+?^${}()|[\]\\]/g, "\\$&").replace(/\*/g, ".*");
  return new RegExp(`^${escaped.endsWith("\\$") ? escaped.slice(0, -2) + "$" : escaped}`);
}

function blockedByRobots(robots, path) {
  const group = robots.groups.find((g) => g.agents.includes("*"));
  if (!group) return false;
  let best = null;
  for (const rule of group.rules) {
    if (!rule.value) continue;
    if (ruleRegex(rule.value).test(path)) {
      if (!best || rule.value.length > best.value.length || (rule.value.length === best.value.length && rule.type === "allow")) best = rule;
    }
  }
  return best?.type === "disallow";
}

const robotsText = site.robots.text ?? "";
const robotsIsHtml = /<!doctype html|<html/i.test(robotsText);
const robots = parseRobots(robotsIsHtml ? "" : robotsText);

// ---------- per-page metadata ----------
const table = [];
const byTitle = new Map();
const byDesc = new Map();
const hostsFromCanonical = new Map();
let noindexCount = 0;

for (const page of pages) {
  const tree = parseHtml(page.html);
  const titleNode = findFirst(tree, "title");
  const title = titleNode ? textOf(titleNode).trim() : "";
  const description = metaContent(tree, "name", "description");
  const robotsMeta = `${metaContent(tree, "name", "robots") ?? ""},${metaContent(tree, "name", "googlebot") ?? ""}`.toLowerCase();
  const xRobots = (page.headers?.["x-robots-tag"] ?? "").toLowerCase();
  const noindex = /noindex|\bnone\b/.test(robotsMeta) || /noindex|\bnone\b/.test(xRobots);
  if (noindex) noindexCount++;
  const canonicals = findAll(tree, (n) => n.tag === "link" && (n.attrs.rel ?? "").toLowerCase().split(/\s+/).includes("canonical"));
  const og = {};
  for (const m of findAll(tree, (n) => n.tag === "meta" && /^og:/i.test(n.attrs.property ?? ""))) og[m.attrs.property.toLowerCase()] = m.attrs.content ?? "";
  const twitter = {};
  for (const m of findAll(tree, (n) => n.tag === "meta" && /^twitter:/i.test(n.attrs.name ?? n.attrs.property ?? ""))) twitter[(m.attrs.name ?? m.attrs.property).toLowerCase()] = m.attrs.content ?? "";
  const icons = findAll(tree, (n) => n.tag === "link" && /(^|\s)(shortcut\s+)?(icon|apple-touch-icon|mask-icon)(\s|$)/i.test(n.attrs.rel ?? ""));
  const ldBlocks = findAll(tree, (n) => n.tag === "script" && /ld\+json/i.test(n.attrs.type ?? ""));

  const row = { path: page.path, title, description, noindex, canonical: canonicals[0]?.attrs.href ?? null, og, twitter, icons: icons.map((i) => i.attrs.href), jsonLdTypes: [] };
  table.push(row);
  const isHome = page.path === "/";
  const where = { page: page.path };

  // title / description
  if (!title) add("META_TITLE_MISSING", isHome ? "HIGH" : "MEDIUM", "OBSERVED", "Page has no <title>.", where);
  else {
    if (STARTER_TITLE.test(title)) add("META_TITLE_STARTER", isHome ? "HIGH" : "MEDIUM", "OBSERVED", `Title "${title}" is a framework/generator default or placeholder.`, where);
    if (title.length > 65) add("META_TITLE_LONG", "LOW", "OBSERVED", `Title is ${title.length} characters and will likely be truncated in results.`, where);
    byTitle.set(title, [...(byTitle.get(title) ?? []), page.path]);
  }
  if (!description) add("META_DESCRIPTION_MISSING", isHome ? "MEDIUM" : "LOW", "OBSERVED", "No meta description. Search engines will pick arbitrary text.", where);
  else {
    if (PLACEHOLDER_DESC.test(description)) add("META_DESCRIPTION_PLACEHOLDER", "MEDIUM", "OBSERVED", `Meta description looks like placeholder text: "${description.slice(0, 80)}".`, where);
    if (description.length > 170) add("META_DESCRIPTION_LONG", "LOW", "OBSERVED", `Meta description is ${description.length} characters.`, where);
    if (description.length < 40) add("META_DESCRIPTION_SHORT", "LOW", "OBSERVED", `Meta description is only ${description.length} characters.`, where);
    byDesc.set(description, [...(byDesc.get(description) ?? []), page.path]);
  }

  // indexing directives
  if (noindex) {
    const sev = isHome ? "HIGH" : HIGH_PRIVATE.test(page.path) || MEDIUM_PRIVATE.test(page.path) ? "INFO" : "MEDIUM";
    add("NOINDEX_PAGE", sev, "OBSERVED", `Page is noindex (${xRobots.includes("noindex") ? "X-Robots-Tag header" : "meta robots"}).${sev === "INFO" ? " That is expected for a private/utility route." : " If this page should be findable, remove it."}`, where);
  }

  // canonical
  if (canonicals.length > 1) add("CANONICAL_MULTIPLE", "MEDIUM", "OBSERVED", `${canonicals.length} canonical links; search engines may ignore all of them.`, where);
  const canonHref = canonicals[0]?.attrs.href?.trim();
  if (!canonHref) {
    if (!noindex) add("CANONICAL_MISSING", "LOW", "OBSERVED", "No canonical link on an indexable page.", where);
  } else {
    let canon = null;
    try {
      canon = new URL(canonHref);
    } catch {
      if (canonHref.startsWith("/")) add("CANONICAL_RELATIVE", "MEDIUM", "OBSERVED", `Canonical "${canonHref}" is relative; use an absolute production URL.`, where);
      else add("CANONICAL_INVALID", "MEDIUM", "OBSERVED", `Canonical "${canonHref}" is not a valid URL.`, where);
    }
    if (canon) {
      hostsFromCanonical.set(canon.host, [...(hostsFromCanonical.get(canon.host) ?? []), page.path]);
      if (DEV_HOST.test(canon.hostname)) add("CANONICAL_LOCALHOST", "HIGH", "OBSERVED", `Canonical points to ${canon.origin}. Search engines will be told the real page lives on a development host.`, { ...where, target: canonHref });
      else if (STAGING_HOST.test(canon.hostname)) add("CANONICAL_STAGING_HOST", "HIGH", "OBSERVED", `Canonical points to a staging-looking host (${canon.hostname}).`, { ...where, target: canonHref });
      else if (PLATFORM_HOST.test(canon.hostname)) add("CANONICAL_PLATFORM_HOST", "LOW", "SOURCE-INDICATED", `Canonical uses a hosting-platform domain (${canon.hostname}). Fine if that is the intended production address; review if a custom domain is planned.`, { ...where, target: canonHref });
      if (canon.protocol === "http:" && !DEV_HOST.test(canon.hostname)) add("CANONICAL_HTTP", "MEDIUM", "OBSERVED", "Canonical uses http://.", { ...where, target: canonHref });
      if (canon.search || canon.hash) add("CANONICAL_QUERY", "LOW", "OBSERVED", "Canonical contains a query string or fragment.", { ...where, target: canonHref });
      row.canonicalPath = normalizePath(canon.pathname);
      if (row.canonicalPath !== normalizePath(page.path) && !/index\.html?$/.test(page.path)) add("CANONICAL_POINTS_ELSEWHERE", "LOW", "OBSERVED", `Page declares ${canon.pathname} as canonical. Correct only if this page is a genuine duplicate of that one.`, { ...where, target: canonHref });
    }
  }

  // Open Graph / Twitter
  const ogImage = og["og:image"];
  const need = (key, sev) => {
    if (!og[key]?.trim()) add(`OG_${key.slice(3).toUpperCase()}_MISSING`, sev, "OBSERVED", `${key} is missing; shared links will have no ${key.slice(3)}.`, where);
  };
  need("og:title", isHome ? "MEDIUM" : "LOW");
  need("og:description", "LOW");
  need("og:image", isHome ? "MEDIUM" : "LOW");
  if (ogImage) {
    if (!/^https?:\/\//i.test(ogImage)) add("OG_IMAGE_RELATIVE", "MEDIUM", "OBSERVED", `og:image "${ogImage}" is not an absolute URL; most crawlers will not resolve it.`, where);
    else {
      let u;
      try {
        u = new URL(ogImage);
      } catch {
        add("OG_IMAGE_INVALID", "MEDIUM", "OBSERVED", `og:image "${ogImage}" is not a valid URL.`, where);
      }
      if (u && DEV_HOST.test(u.hostname)) add("OG_IMAGE_LOCALHOST", "MEDIUM", "OBSERVED", `og:image points at ${u.hostname}; it will not load for anyone else.`, where);
      if (u && /\.svg(\?|$)/i.test(u.pathname)) add("OG_IMAGE_SVG", "LOW", "OBSERVED", "og:image is an SVG; most social platforms do not render SVG previews.", where);
      if (u && STARTER_ASSET.test(u.pathname)) add("OG_IMAGE_PLACEHOLDER", "LOW", "OBSERVED", `og:image looks like a starter/placeholder asset (${u.pathname}).`, where);
    }
  }
  if (og["og:url"] && row.canonical && og["og:url"].replace(/\/$/, "") !== row.canonical.replace(/\/$/, "")) add("OG_URL_CANONICAL_MISMATCH", "LOW", "OBSERVED", `og:url (${og["og:url"]}) differs from canonical (${row.canonical}).`, where);
  if (!twitter["twitter:card"] && !noindex) add("TWITTER_CARD_MISSING", "INFO", "OBSERVED", "No twitter:card. Platforms fall back to Open Graph but default to a small card.", where);

  // favicon
  if (isHome) {
    if (icons.length === 0) row.faviconImplicit = true;
    for (const icon of icons) {
      if (STARTER_ASSET.test(icon.attrs.href ?? "")) add("FAVICON_STARTER", "LOW", "OBSERVED", `Favicon ${icon.attrs.href} looks like a framework starter asset.`, where);
    }
  }

  // JSON-LD
  for (const block of ldBlocks) {
    const raw = (block.children[0]?.text ?? "").trim();
    try {
      const data = JSON.parse(raw);
      const types = [].concat(data["@graph"] ?? data).map((d) => d?.["@type"]).flat().filter(Boolean);
      row.jsonLdTypes.push(...types);
      if (/localhost|127\.0\.0\.1/.test(raw)) add("JSONLD_LOCALHOST", "MEDIUM", "OBSERVED", "Structured data contains a localhost URL.", where);
    } catch {
      add("JSONLD_INVALID", "MEDIUM", "OBSERVED", "JSON-LD block is not valid JSON; search engines will ignore it.", where);
    }
  }
}

for (const [title, paths] of byTitle) if (paths.length > 1) add("META_TITLE_DUPLICATE", "MEDIUM", "OBSERVED", `${paths.length} pages share the title "${title.slice(0, 70)}": ${paths.slice(0, 5).join(", ")}.`, { target: title });
for (const [d, paths] of byDesc) if (paths.length > 1) add("META_DESCRIPTION_DUPLICATE", "LOW", "OBSERVED", `${paths.length} pages share one meta description: ${paths.slice(0, 5).join(", ")}.`, { target: d.slice(0, 80) });
const byCanonical = new Map();
for (const row of table) if (row.canonical && !row.noindex) byCanonical.set(row.canonical, [...(byCanonical.get(row.canonical) ?? []), row.path]);
for (const [canonical, paths] of byCanonical) {
  if (paths.length > 1) add("CANONICAL_DUPLICATE_TARGET", "MEDIUM", "OBSERVED", `${paths.length} different pages declare the same canonical ${canonical} (${paths.slice(0, 4).join(", ")}). Only one page can be canonical for that URL; this is often a template copied from the home page, and it tells search engines to ignore the others.`, { target: canonical });
}
if (hostsFromCanonical.size > 1) add("CANONICAL_HOST_INCONSISTENT", "MEDIUM", "OBSERVED", `Canonicals use different hosts: ${[...hostsFromCanonical].map(([h, p]) => `${h} (${p.length})`).join(", ")}.`);
if (pages.length > 1 && noindexCount === pages.length) add("NOINDEX_SITEWIDE", "HIGH", "OBSERVED", "Every inspected page is noindex. This is a common staging leftover and prevents the launch from being found.");

// favicon existence (once)
const home = pages.find((p) => p.path === "/") ?? pages[0];
if (home) {
  const homeRow = table.find((r) => r.path === home.path);
  const hrefs = homeRow?.icons.length ? homeRow.icons : ["/favicon.ico"];
  for (const href of hrefs) {
    let exists;
    try {
      const u = new URL(href, home.finalUrl ?? `http://dir.local${home.path}`);
      if (site.mode === "dir") exists = site.known.has(u.pathname);
      else if (u.origin === site.origin) {
        const res = await fetchWithRetry(u.href, { timeoutMs: Number(args.timeout) }, 1);
        exists = res.ok ? res.status === 200 : undefined;
      }
    } catch {
      exists = undefined;
    }
    if (exists === false) add(homeRow?.icons.length ? "FAVICON_BROKEN" : "FAVICON_MISSING", "LOW", "OBSERVED", homeRow?.icons.length ? `Favicon link ${href} does not resolve.` : "No favicon link and /favicon.ico does not exist. Browser tabs and bookmarks show a blank icon.", { page: home.path, target: href });
  }
}

// ---------- robots.txt ----------
if (site.robots.status === 404 || (!robotsText && !site.robots.error)) add("ROBOTS_MISSING", "INFO", "OBSERVED", "No robots.txt. Crawling is allowed by default, so this is not a defect by itself.");
else if (site.robots.error) notes.push(`robots.txt could not be fetched (${site.robots.error}); robots checks skipped.`);
else if (robotsIsHtml) add("ROBOTS_IS_HTML", "MEDIUM", "OBSERVED", "/robots.txt returns an HTML page (often the app's index.html via a catch-all rewrite). Crawlers will ignore it.");
else {
  const star = robots.groups.find((g) => g.agents.includes("*"));
  if (star?.rules.some((r) => r.type === "disallow" && r.value === "/") && !star.rules.some((r) => r.type === "allow" && r.value === "/")) add("ROBOTS_DISALLOW_ALL", "HIGH", "OBSERVED", "robots.txt disallows the entire site for all crawlers. Correct only for staging or private products; a launch that should be found will not be.");
  for (const rule of star?.rules ?? []) {
    if (rule.type !== "disallow" || !rule.value) continue;
    if (/^\/(_next|static|assets|build|dist)\b|\.(css|js)\$?$/.test(rule.value)) add("ROBOTS_BLOCKS_ASSETS", "MEDIUM", "OBSERVED", `robots.txt blocks ${rule.value}; crawlers need CSS/JS to render the page.`);
    if (HIGH_PRIVATE.test(rule.value) && !/^\/(_next|static|assets)/.test(rule.value)) add("ROBOTS_ADVERTISES_PRIVATE_PATH", "LOW", "SOURCE-INDICATED", `robots.txt lists ${rule.value}. robots.txt is public and is not access control; confirm that route requires authentication.`, { target: rule.value });
  }
  if (robots.sitemaps.length === 0 && site.sitemaps.some((s) => s.status === 200 && s.text)) add("ROBOTS_NO_SITEMAP_DIRECTIVE", "INFO", "OBSERVED", "robots.txt does not declare the sitemap that exists.");
  for (const declared of robots.sitemaps) {
    let u;
    try {
      u = new URL(declared);
    } catch {
      add("ROBOTS_SITEMAP_RELATIVE", "MEDIUM", "OBSERVED", `Sitemap directive "${declared}" must be an absolute URL.`, { target: declared });
      continue;
    }
    if (DEV_HOST.test(u.hostname)) add("ROBOTS_SITEMAP_LOCALHOST", "HIGH", "OBSERVED", `robots.txt points crawlers at a development sitemap (${declared}).`, { target: declared });
    else if (STAGING_HOST.test(u.hostname)) add("ROBOTS_SITEMAP_STAGING", "HIGH", "OBSERVED", `robots.txt points crawlers at a staging sitemap (${declared}).`, { target: declared });
  }
}

if (robots.groups.length) {
  for (const row of table) {
    const path = normalizePath(row.path);
    if (!row.noindex && !HIGH_PRIVATE.test(path) && !MEDIUM_PRIVATE.test(path) && blockedByRobots(robots, path)) add("ROBOTS_BLOCKS_PAGE", "MEDIUM", "OBSERVED", `robots.txt blocks ${path}, a public indexable page that is linked from the site. Crawlers cannot read it, so its title, description, and noindex directive are never seen.`, { page: row.path });
  }
}

// ---------- sitemap ----------
const sitemapDocs = site.sitemaps.filter((s) => s.status === 200 && s.text);
const canonicalOf = new Map(table.map((r) => [normalizePath(r.path), r.canonicalPath]));
const noindexPaths = new Set(table.filter((r) => r.noindex).map((r) => normalizePath(r.path)));
const indexablePaths = new Set(table.filter((r) => !r.noindex).map((r) => normalizePath(r.path)));
const listedPaths = new Set();
if (sitemapDocs.length === 0) {
  const declaredButMissing = robots.sitemaps.length > 0;
  if (declaredButMissing) add("SITEMAP_DECLARED_BUT_MISSING", "MEDIUM", "OBSERVED", "robots.txt declares a sitemap but the sitemap could not be fetched from the inspected site.");
  else if (indexablePaths.size >= 4) add("SITEMAP_MISSING", "LOW", "OBSERVED", `No sitemap.xml found and ${indexablePaths.size} indexable pages were discovered.`);
  else add("SITEMAP_MISSING", "INFO", "OBSERVED", "No sitemap.xml. Optional for a very small site.");
}
for (const map of sitemapDocs) {
  if (/<!doctype html|<html/i.test(map.text)) {
    add("SITEMAP_IS_HTML", "MEDIUM", "OBSERVED", `${map.url} returns an HTML page instead of XML (likely a catch-all rewrite).`);
    continue;
  }
  if (!/<urlset|<sitemapindex/i.test(map.text)) {
    add("SITEMAP_INVALID", "MEDIUM", "OBSERVED", `${map.url} is not a valid sitemap (no <urlset> or <sitemapindex>).`);
    continue;
  }
  if (/<sitemapindex/i.test(map.text)) continue;
  if (!/xmlns\s*=\s*["']http:\/\/www\.sitemaps\.org/i.test(map.text)) add("SITEMAP_NO_NAMESPACE", "LOW", "OBSERVED", "<urlset> lacks the sitemaps.org xmlns; some parsers reject it.", { page: map.url });
  const locs = extractLocs(map.text);
  if (locs.length > 50000) add("SITEMAP_TOO_LARGE", "MEDIUM", "OBSERVED", `${locs.length} URLs; the limit is 50,000 per file.`, { page: map.url });
  const hosts = new Map();
  const seen = new Set();
  const schemes = new Set();
  for (const loc of locs) {
    let u;
    try {
      u = new URL(loc);
    } catch {
      add("SITEMAP_LOC_INVALID", "MEDIUM", "OBSERVED", `<loc> "${loc}" is not an absolute URL.`, { page: map.url, target: loc });
      continue;
    }
    hosts.set(u.host, (hosts.get(u.host) ?? 0) + 1);
    schemes.add(u.protocol);
    const path = normalizePath(u.pathname);
    listedPaths.add(path);
    if (seen.has(u.href)) add("SITEMAP_DUPLICATE_URL", "LOW", "OBSERVED", `${loc} is listed more than once.`, { page: map.url, target: loc });
    seen.add(u.href);
    if (DEV_HOST.test(u.hostname)) add("SITEMAP_LOCALHOST", "HIGH", "OBSERVED", `Sitemap lists a development URL (${loc}).`, { page: map.url, target: loc });
    else if (STAGING_HOST.test(u.hostname)) add("SITEMAP_STAGING_HOST", "HIGH", "OBSERVED", `Sitemap lists a staging URL (${loc}).`, { page: map.url, target: loc });
    if (HIGH_PRIVATE.test(path) || extraPrivate.some((p) => path === p || path.startsWith(`${p}/`))) add("SITEMAP_PRIVATE_ROUTE", "HIGH", "OBSERVED", `Sitemap advertises ${path}, which looks like a private/internal route. Advertising it invites crawling and exposure.`, { page: map.url, target: loc });
    else if (MEDIUM_PRIVATE.test(path)) add("SITEMAP_UTILITY_ROUTE", "MEDIUM", "OBSERVED", `Sitemap lists ${path}, a login/account/checkout-style route. These are rarely worth indexing; review the intent.`, { page: map.url, target: loc });
    if (noindexPaths.has(path)) add("SITEMAP_NOINDEX_LISTED", "MEDIUM", "OBSERVED", `${path} is listed in the sitemap but is noindex. The two signals contradict each other.`, { page: map.url, target: loc });
    if (robots.groups.length && blockedByRobots(robots, path)) add("SITEMAP_ROBOTS_BLOCKED", "MEDIUM", "OBSERVED", `${path} is listed in the sitemap but blocked by robots.txt.`, { page: map.url, target: loc });
    const canon = canonicalOf.get(path);
    if (canon && canon !== path) add("SITEMAP_NON_CANONICAL", "MEDIUM", "OBSERVED", `${path} is listed but its canonical is ${canon}. Sitemaps should list canonical URLs only.`, { page: map.url, target: loc });
  }
  if (schemes.size > 1) add("SITEMAP_SCHEME_MIXED", "LOW", "OBSERVED", "Sitemap mixes http and https URLs.", { page: map.url });
  const dominant = [...hosts].sort((a, b) => b[1] - a[1])[0]?.[0];
  const canonicalHost = [...hostsFromCanonical].sort((a, b) => b[1].length - a[1].length)[0]?.[0];
  if (dominant && canonicalHost && dominant !== canonicalHost && !DEV_HOST.test(canonicalHost.split(":")[0]) && !DEV_HOST.test(dominant.split(":")[0])) add("SITEMAP_HOST_MISMATCH", "MEDIUM", "OBSERVED", `Sitemap URLs use ${dominant} but page canonicals use ${canonicalHost}.`, { page: map.url });
  if (hosts.size > 1) add("SITEMAP_MULTIPLE_HOSTS", "MEDIUM", "OBSERVED", `Sitemap lists URLs from several hosts: ${[...hosts.keys()].join(", ")}.`, { page: map.url });
  const missing = [...indexablePaths].filter((p) => !listedPaths.has(p) && !HIGH_PRIVATE.test(p) && !MEDIUM_PRIVATE.test(p));
  if (locs.length && missing.length) add("SITEMAP_INCOMPLETE", "LOW", "OBSERVED", `${missing.length} indexable page(s) discovered by crawling are not in the sitemap: ${missing.slice(0, 5).join(", ")}${missing.length > 5 ? "…" : ""}.`, { page: map.url });
}
notes.push("Sitemap and canonical target status codes are checked by check-links.mjs; run it for SITEMAP_URL_BROKEN and CANONICAL_TARGET_BROKEN.");
emit("inspect-metadata", { mode: site.mode, pagesInspected: pages.length, pages: table, findings, notes }, args.json);
